interface LanguageContextValue {
  language: AppLanguage
  setLanguage: (language: AppLanguage) => void
  t: (text: string) => string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

function translateDynamic(language: AppLanguage, text: string) {
  if (language === 'en') return text
  const rain = text.match(/^Scenario rainfall (reaches|is) ([\d.]+) mm, (at or above|below) the selected ([\d.]+) mm threshold\.$/)
  if (rain) {
    const [, , amount, comparison, threshold] = rain
    if (language === 'mr') return comparison === 'below' ? `परिस्थितीतील पाऊस ${amount} मिमी आहे; निवडलेल्या ${threshold} मिमी मर्यादेपेक्षा कमी.` : `परिस्थितीतील पाऊस ${amount} मिमी आहे; निवडलेल्या ${threshold} मिमी मर्यादेइतका किंवा अधिक.`
    return comparison === 'below' ? `परिदृश्य में वर्षा ${amount} मिमी है; चुनी गई ${threshold} मिमी सीमा से कम।` : `परिदृश्य में वर्षा ${amount} मिमी है; चुनी गई ${threshold} मिमी सीमा के बराबर या अधिक।`
  }
  const temperature = text.match(/^Scenario temperature is ([\d.]+) °C; baseline-based advisories update with this adjustment\.$/)
  if (temperature) return language === 'mr' ? `परिस्थितीतील तापमान ${temperature[1]} °C आहे; या बदलानुसार आधारभूत सल्ले अद्ययावत होतात.` : `परिदृश्य का तापमान ${temperature[1]} °C है; इस बदलाव के अनुसार आधार सलाह अपडेट होती है।`
  const soil = text.match(/^Soil-moisture context is set to (low|medium|high); this is a user scenario assumption, not a measured soil-moisture value\.$/)
  if (soil) {
    const level = language === 'mr' ? ({ low: 'कमी', medium: 'मध्यम', high: 'जास्त' } as const)[soil[1] as 'low' | 'medium' | 'high'] : ({ low: 'कम', medium: 'मध्यम', high: 'अधिक' } as const)[soil[1] as 'low' | 'medium' | 'high']
    return language === 'mr' ? `जमिनीतील ओलाव्याची स्थिती ${level} ठेवली आहे; हा वापरकर्त्याचा परिस्थिती-अंदाज आहे, मोजलेले मूल्य नाही.` : `मिट्टी की नमी ${level} मानी गई है; यह उपयोगकर्ता की परिदृश्य धारणा है, मापा गया मान नहीं।`
  }
  return text
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<AppLanguage>(() => {
    const saved = window.localStorage.getItem('hyperweather-language')
    return saved === 'mr' || saved === 'hi' ? saved : 'en'
  })
  useEffect(() => window.localStorage.setItem('hyperweather-language', language), [language])
  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage,
    t: text => translations[language][text] ?? translateDynamic(language, text),
  }), [language])
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const value = useContext(LanguageContext)
  if (!value) throw new Error('useLanguage must be used inside LanguageProvider.')
  return value
}
