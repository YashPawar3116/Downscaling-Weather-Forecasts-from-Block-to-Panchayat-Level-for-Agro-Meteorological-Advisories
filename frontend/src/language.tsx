interface LanguageContextValue {
  language: AppLanguage
  setLanguage: (language: AppLanguage) => void
  t: (text: string) => string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<AppLanguage>(() => {
    const saved = window.localStorage.getItem('hyperweather-language')
    return saved === 'mr' || saved === 'hi' ? saved : 'en'
  })
  useEffect(() => window.localStorage.setItem('hyperweather-language', language), [language])
  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage,
    t: text => translations[language][text] ?? text,
  }), [language])
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const value = useContext(LanguageContext)
  if (!value) throw new Error('useLanguage must be used inside LanguageProvider.')
  return value
}
